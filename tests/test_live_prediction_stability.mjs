import assert from 'node:assert/strict';
import {MotionTracker} from '../motion_tracker.mjs';

const w=120,h=90;
const gray=new Uint8Array(w*h).fill(22);
const tracker=new MotionTracker({maxDetectionAgeMs:3000,maxMissingFrames:6});
const capture=tracker.addFrame(gray,w,h,100);
const detected=(label,conf,bb)=>[{label,confidence:conf,bbox:bb}];
const first=detected('Resistor',.86,[.22,.22,.43,.47]);
assert(tracker.ingestDetections(first,capture,110));
const id=tracker.getDetections()[0].trackId;
const jitter=detected('Resistor',.78,[.221,.221,.431,.471]);
assert(tracker.ingestDetections(jitter,capture,150));
const stable=tracker.getDetections()[0];
assert.equal(stable.trackId,id,'same object should keep ID');
assert.equal(stable.label,'Resistor');
assert.equal(stable.confidence,.78,'never invent confidence or reuse old YOLO score');
assert(stable.bbox[0]>.22&&stable.bbox[0]<.221,'small YOLO jitter should be damped');
assert(tracker.ingestDetections(detected('Resistor',.77,[.56,.50,.75,.74]),capture,180));
const moved=tracker.getDetections()[0];
assert.equal(moved.bbox[0],.56,'fast object movement must not be smoothed toward old position');
assert.notEqual(moved.trackId,id,'big jump should not inherit a stale track ID');
assert(tracker.ingestDetections(detected('LED',.94,[.56,.50,.75,.74]),capture,190));
assert.equal(tracker.getDetections()[0].label,'LED','new YOLO result must update class');
assert(tracker.ingestDetections([],capture,200));
assert.deepEqual(tracker.getDetections(),[],'negative YOLO result clears boxes');
tracker.ingestDetections(first,capture,210);
tracker.addFrame(gray,w,h,3300);
assert.deepEqual(tracker.getDetections(),[],'ghost boxes removed after max age');
console.log('YOLO track smoothing, class changes, fast movement and expiry: PASS');
